#!/usr/bin/env python3
"""The repository's own index: what each build is, which register is canonical, and where IDs collide.

    python3 -m injury_lab.builds

Three tables, all recomputed from the tree rather than copied from a README, because the prose index in
this repository has already drifted: it announced page counts that were wrong, and the board recorded that
as irregularity N11.

``builds``       one row per published surface, with its page count and table-row count counted from the
                 files on disk, the session that owns it per COORDINATION.md, and a status of canonical,
                 preserved or superseded. Statuses are assertions about purpose, and every one cites the
                 board line or the file that says it.

``registers``    every suggestions and questions register in the tree, with the entry count of each and
                 which page publishes it, so "the suggestions board" stops being ambiguous.

``id_collision`` the strategy-ID and gate-ID collision crosswalk, computed by reading the ledgers:
                 two strategy namespaces share the numeric part of their IDs (S1..S11 and S01..S18), and
                 two gate registers reuse G1..G8 for different rules. The table shows the actual names
                 under each ID in each file, so a reader can see the hazard instead of being told about it.
"""
from __future__ import annotations

import csv
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DATA = HERE / "data"

SURFACES = [
    ("root", "*.html at the repository root", "line_lab", "line_lab/build_site.py",
     "canonical for the empirical root dashboard; regenerated by its own generator"),
    ("hub/", "hub/*.html", "hub", "hub/build_hub.py",
     "consolidated dashboard; board records hub/questions.html and hub/suggestions.html as canonical "
     "registers from session arena/6cbe5d15-korea3"),
    ("decision_lab/", "decision_lab/*.html", "decision_lab", "decision_lab/build.py",
     "pre-decision pack: suggestions, open questions, injury/depth capability; fail-closed checker R1-R14"),
    ("decisions/", "decisions/*.html", "decisions", "decisions/build.py",
     "a second decision-readiness surface, added by session arena/7f33cb21-korea3 (PR #69)"),
    ("verified/", "verified/*.html", "verified", "nfl_lab/build_verified.py",
     "official-evidence-only workbench; unverified values blank"),
    ("site/", "site/*.html", "site", "scripts/build_site.py", "empirical pipeline site; site/prior* mirrors"),
    ("docs/", "docs/*.html", "docs", "pipeline/build_site.py",
     "second Line Lab build, left byte-identical so its CI gate keeps passing"),
    ("qa/", "qa/*.html", "qa", "qa/build_site.py", "independent QA site"),
    ("audit/", "audit/*.html", "audit", "-", "independent audit page set"),
    ("review/", "review/*.html", "review", "-", "single-session review pages"),
    ("injury_lab/", "injury_lab/*.html", "injury_lab", "injury_lab/build_site.py",
     "this session: injury and depth capture, the join, the pre-registered injury family"),
]

STRATEGY_LEDGERS = [
    ("data/derived/bets.csv", "strategy_id", "strategy_name", "scripts/ (session arena/c70bdb9d-korea3)"),
    ("line_lab/data/derived/bets.csv", "strategy_id", "strategy_name", "line_lab (session arena/9f5e9cb5-korea3)"),
    ("data/derived/gates_results.csv", "id", "name", "scripts/gates.py output (same build as row 1)"),
    ("reports/strategies.json", None, None, "pipeline/ (session arena/d118ca7e-korea3)"),
    ("verified/data/strategies.json", None, None, "nfl_lab/ (session arena/cbcd97cc-korea3)"),
]

REGISTER_GLOBS = {
    "suggestions": ["hub/suggestions.html", "decision_lab/suggestions.html", "decisions/suggestions.html",
                    "suggestions.html", "site/prior/strategies.html"],
    "questions": ["hub/questions.html", "decision_lab/open-questions.html", "decisions/questions.html",
                  "decisions/data/questions.json", "decision_lab/data/questions.json"],
    "flags": ["hub/flagged.html", "decision_lab/flagged.html", "flagged.html", "audit/flagged.html",
              "verified/flagged.html", "docs/flagged-for-review.html", "qa/flagged.html", "review/flagged.html"],
}


def html_row_count(path: Path) -> int:
    html = path.read_text(encoding="utf-8", errors="replace")
    return html.count("<tr")


def json_entries(path: Path) -> int:
    try:
        d = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return -1
    if isinstance(d, dict):
        for key in ("suggestions", "questions", "rows", "flags", "items", "entries"):
            if isinstance(d.get(key), list):
                return len(d[key])
    return len(d) if isinstance(d, list) else -1


def strategies_from_csv(rel: str, idcol: str, namecol: str) -> dict[str, str]:
    out: dict[str, str] = {}
    path = ROOT / rel
    if not path.is_file():
        return out
    with path.open(newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            key = (row.get(idcol) or "").strip()
            if key:
                out.setdefault(key, (row.get(namecol) or "").strip())
    return out


def strategies_from_json(rel: str) -> dict[str, str]:
    path = ROOT / rel
    out: dict[str, str] = {}
    if not path.is_file():
        return out
    d = json.loads(path.read_text(encoding="utf-8"))
    items = d.get("strategies") if isinstance(d, dict) else d
    for item in items or []:
        if isinstance(item, dict) and item.get("id"):
            out.setdefault(item["id"], item.get("name", ""))
    return out


def main() -> int:
    # ---- surfaces ------------------------------------------------------------------
    surfaces = []
    for name, glob, owner, generator, status in SURFACES:
        base = ROOT if name == "root" else ROOT / name.rstrip("/")
        if name == "root":
            pages = sorted(p for p in ROOT.glob("*.html"))
        else:
            pages = sorted(base.rglob("*.html"))
        rows = sum(html_row_count(p) for p in pages)
        surfaces.append({"surface": name, "pages_found": len(pages), "tr_tags_found": rows,
                         "generator": generator, "board_owner": owner, "status": status,
                         "first_pages": [p.name for p in pages[:6]]})

    # ---- registers -----------------------------------------------------------------
    registers = []
    for kind, rels in REGISTER_GLOBS.items():
        for rel in rels:
            path = ROOT / rel
            if not path.is_file():
                registers.append({"kind": kind, "path": rel, "entries": 0, "state": "file absent"})
                continue
            n = json_entries(path) if rel.endswith(".json") else html_row_count(path)
            registers.append({"kind": kind, "path": rel, "entries": n,
                              "state": "present",
                              "how_counted": "JSON array length" if rel.endswith(".json")
                                             else "<tr> count, which includes header rows"})
    board = (ROOT / "COORDINATION.md").read_text(encoding="utf-8")
    for reg in registers:
        reg["named_canonical_on_the_board"] = f"`{reg['path']}`" in board or reg["path"] in board

    # ---- ID collisions -------------------------------------------------------------
    ledgers = {}
    for rel, idcol, namecol, owner in STRATEGY_LEDGERS:
        ledgers[rel] = (strategies_from_csv(rel, idcol, namecol) if idcol
                        else strategies_from_json(rel))
        ledgers[rel + "::owner"] = owner
    def norm(key: str) -> str:
        """S01 and S1 are the same rule number in a different format.

        Two ledgers in this repository name their rules with zero padding and one does not, so any tool
        that keys a lookup on the raw string treats them as separate namespaces and any tool that joins on
        a stripped int silently merges them. Both behaviours are hazards, which is why the collision is
        computed here on a normalised key and published, rather than asserted in prose.
        """
        m = re.fullmatch(r"([A-Z]+)0*(\d+)", key.strip())
        return f"{m.group(1)}{int(m.group(2))}" if m else key.strip()
    collisions: dict[str, dict[str, str]] = {}
    for rel, ids in ledgers.items():
        if rel.endswith("::owner") or isinstance(ids, str):
            continue
        for k, v in ids.items():
            collisions.setdefault(norm(k), {})[rel] = v
    clash_rows = []
    for key, per_file in sorted(collisions.items()):
        if len(per_file) < 2:
            continue
        names = sorted({v for v in per_file.values()})
        clash_rows.append({"normalised_id": key, "ledgers": per_file,
                           "distinct_names": len(names),
                           "collides": len(names) > 1})
    gate_registers = {}
    gates_src = (ROOT / "scripts" / "gates.py").read_text(encoding="utf-8").splitlines()
    for line in gates_src[:20]:
        m = re.match(r"\s*G(\d)\s+(.*?)\s{2,}(.*?)\s*$", line)
        if m:
            gate_registers.setdefault(f"G{m.group(1)}", {})["scripts/gates.py"] = m.group(2).strip()
    for line in (ROOT / "docs" / "preregistration.md").read_text(encoding="utf-8").splitlines():
        m = re.match(r"\|\s*(G\d)\s+([^|]*)\|", line)
        if m:
            gate_registers.setdefault(m.group(1), {})["docs/preregistration.md"] = m.group(2).strip()
    gate_clash = [{"gate": g, "meanings": v, "same_rule": len(set(v.values())) == 1}
                  for g, v in sorted(gate_registers.items()) if len(v) > 1]

    out = {
        "_comment": ["Generated by injury_lab/builds.py. Counts are taken from the files on disk at build "
                     "time; nothing here is copied from a README, because the README's counts have been "
                     "wrong before (board flag N11).",
                     "Status words describe what a surface was built to be. They are read off "
                     "COORDINATION.md and cited per row; they are not a proposal to delete anything."],
        "generated_by": "injury_lab/builds.py",
        "surfaces": surfaces,
        "registers": registers,
        "strategy_id_collisions": clash_rows,
        "gate_id_collisions": gate_clash,
        "ledger_sizes": {rel: len(ids) for rel, ids in ledgers.items() if not rel.endswith("::owner")},
        "ledger_owners": {rel: v for rel, v in ledgers.items() if rel.endswith("::owner")},
    }
    DATA.mkdir(parents=True, exist_ok=True)
    (DATA / "builds.json").write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
    pages = sum(s["pages_found"] for s in surfaces)
    print(f"builds: {len(surfaces)} surfaces, {pages} html pages, {len(registers)} registers, "
          f"{len(clash_rows)} colliding strategy ids, {len(gate_clash)} colliding gate ids")
    for row in clash_rows[:6]:
        print("  ", row["normalised_id"], "->", {k.split('/')[0]: v[:24] for k, v in row["ledgers"].items()})
    for row in gate_clash[:8]:
        print("  ", row["gate"], row["meanings"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
